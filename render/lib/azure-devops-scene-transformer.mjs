function renderTabs(variant) {
  const active = variant === 'pr-overview' || variant === 'pr-diff' || variant === 'assistant-comment' || variant === 'reviewer-activity' ? 'pulls'
    : variant === 'file-view' || variant === 'repo-files' ? 'files'
      : 'files';
  const tabs = [
    ['files', 'Files'],
    ['commits', 'Commits'],
    ['pulls', 'Pull requests'],
    ['branches', 'Branches'],
    ['tags', 'Tags']
  ];
  return tabs.map(([key, label]) => `<div class="ado-tab${key === active ? ' ado-tab--active' : ''}">${escapeHtml(label)}</div>`).join('');
}

function renderTree(rows) {
  const data = Array.isArray(rows) && rows.length ? rows : [
    { name: 'src', type: 'folder', indent: 0 },
    { name: 'platform', type: 'folder', indent: 1 },
    { name: 'contracts', type: 'folder', indent: 2, active: true },
    { name: 'tests', type: 'folder', indent: 0 },
    { name: '.azuredevops', type: 'folder', indent: 0 },
    { name: 'README.md', type: 'file', indent: 0 }
  ];
  return data.map((row) => {
    const typeName = row.type === 'file' ? 'file' : 'folder';
    const icon = typeName === 'file' ? 'doc' : 'dir';
    const indent = Math.max(0, Math.min(2, Number(row.indent || 0)));
    return `<div class="ado-tree-row ado-tree-indent-${indent}${row.active ? ' ado-tree-row--active' : ''}"><span class="ado-tree-icon">${icon}</span><span>${escapeHtml(row.name || 'item')}</span></div>`;
  }).join('');
}

