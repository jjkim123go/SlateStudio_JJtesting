function escapeHtml(value) {
  if (value == null) return '';
  return String(value)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

function hasText(value) {
  return typeof value === 'string' && value.trim().length > 0;
}

function text(value, fallback) {
  return hasText(value) ? String(value) : fallback;
}

function initials(name, fallback = 'AB') {
  if (!hasText(name)) return fallback;
  const parts = String(name).trim().split(/\s+/).slice(0, 2);
  return parts.map((part) => part.charAt(0).toUpperCase()).join('') || fallback;
}

function normalizeStatus(status) {
  const s = String(status || 'info').toLowerCase();
  if (['success', 'passed', 'approved', 'complete', 'ok'].includes(s)) return 'success';
  if (['warning', 'attention', 'waiting', 'pending'].includes(s)) return 'warning';
  if (['danger', 'failed', 'blocked', 'error'].includes(s)) return 'danger';
  return 'info';
}

function statusLabel(status) {
  const s = normalizeStatus(status);
  if (s === 'success') return 'OK';
  if (s === 'warning') return 'Review';
  if (s === 'danger') return 'Block';
  return 'Info';
}

function statusIcon(status) {
  const s = normalizeStatus(status);
  if (s === 'success') return '✓';
  if (s === 'warning') return '!';
  if (s === 'danger') return '×';
  return 'i';
}

function statusPill(label, status = 'info') {
  const cls = normalizeStatus(status);
  return `<span class="ado-status ado-status--${cls}">${escapeHtml(label || statusLabel(cls))}</span>`;
}

