function renderCode(lines) {
  const data = Array.isArray(lines) && lines.length ? lines : [
    'class BillingGroupContract:',
    '    version = "2026.04"',
    '    required_fields = ["invoice_id", "amount", "currency"]',
    '    downstream_contracts = ["collector", "ledger"]',
    '',
    'def validate(record):',
    '    return all(field in record for field in required_fields)'
  ];
  return data.map((line, index) => {
    const row = typeof line === 'string' ? { text: line } : line;
    const number = row.number == null ? index + 1 : row.number;
    return `<div class="ado-code-row${row.highlight ? ' ado-code-row--highlight' : ''}"><div class="ado-code-num">${escapeHtml(number)}</div><div class="ado-code-text">${escapeHtml(row.text || '')}</div></div>`;
  }).join('');
}

function renderDiff(lines) {
  const data = Array.isArray(lines) && lines.length ? lines : [
    { type: 'hunk', text: '@@ contract fields @@' },
    { type: 'context', text: 'required_fields = ["invoice_id", "amount", "currency"]' },
    { type: 'remove', text: 'downstream_contracts = ["collector"]' },
    { type: 'add', text: 'downstream_contracts = ["collector", "ledger"]' },
    { type: 'add', text: 'owner_review_required = true' }
  ];
  return data.map((line, index) => {
    const typeName = ['add', 'remove', 'hunk'].includes(line.type) ? line.type : 'context';
    const prefix = typeName === 'add' ? '+' : typeName === 'remove' ? '-' : typeName === 'hunk' ? '@' : ' ';
    const num = line.newNumber || line.oldNumber || (typeName === 'hunk' ? '' : index + 1);
    return `<div class="ado-diff-row ado-diff-row--${typeName}"><div class="ado-diff-num">${escapeHtml(num)}</div><div class="ado-diff-text">${escapeHtml(prefix + ' ' + (line.text || ''))}</div></div>`;
  }).join('');
}

