function renderBody(props) {
  if (hasText(props.bodyHtml)) return props.bodyHtml;
  switch (props.variant) {
    case 'file-view': return renderFileView(props);
    case 'pr-overview': return renderPrOverview(props);
    case 'pr-diff': return renderPrDiff(props);
    case 'assistant-comment': return renderAssistantComment(props);
    case 'reviewer-activity': return renderReviewerActivity(props);
    case 'repo-files':
    default: return renderRepoFiles(props);
  }
}

export function transformAzureDevOpsScene(props) {
  if (!props || typeof props !== 'object') return;
  props.variant = text(props.variant, 'repo-files');
  props.theme = text(props.theme, 'sky-premium');
  props.projectName = text(props.projectName, 'Commerce Platform');
  props.repoName = text(props.repoName, 'Commerce-Financials-Controls');
  props.branchName = text(props.branchName, 'main');
  props.userInitials = text(props.userInitials, 'AB');
  props.searchPlaceholder = text(props.searchPlaceholder, 'Search project, files, work items, or PRs');
  props.breadcrumb = text(props.breadcrumb, `${props.projectName} / Repos / ${props.repoName}`);
  props.pageTitle = text(props.pageTitle, props.variant.startsWith('pr') || props.variant === 'assistant-comment' || props.variant === 'reviewer-activity' ? 'Pull request 10427' : 'Repository files');
  props.subtitle = text(props.subtitle, 'An anonymized Azure DevOps surface for explaining repositories, pull requests, and PR Assistant review flow.');
  if (!hasText(props.sideNavHtml)) props.sideNavHtml = renderSideNav('repos');
  if (!hasText(props.tabsHtml)) props.tabsHtml = renderTabs(props.variant);
  if (!hasText(props.headerPillsHtml)) {
    const pills = [
      statusPill(props.branchName, 'info'),
      props.variant.includes('pr') || props.variant === 'assistant-comment' || props.variant === 'reviewer-activity' ? statusPill('Active PR', 'warning') : statusPill('Demo data', 'success')
    ];
    props.headerPillsHtml = pills.join('');
  }
  props.bodyHtml = renderBody(props);
}